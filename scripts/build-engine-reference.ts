/** Writes the agent's engine reference (packages/scene-engine/reference/api.md) as a TypeScript string module, so every
 * build tool can include it in the cached system prompt. A unit test fails if the two drift apart. */
import {readFileSync,writeFileSync} from 'node:fs';
import {resolve} from 'node:path';
export function engineReferenceModule(markdown:string){return `// Generated by scripts/build-engine-reference.ts from reference/api.md. Do not edit by hand.\nexport const engineReference=${JSON.stringify(markdown.replace(/\r\n/g,'\n'))};\n`;}
if(process.argv[1]?.endsWith('build-engine-reference.ts')){
 const markdown=readFileSync(resolve('packages/scene-engine/reference/api.md'),'utf8');
 writeFileSync(resolve('packages/scene-engine/src/reference.generated.ts'),engineReferenceModule(markdown));
 console.log('Engine reference module written.');
}
